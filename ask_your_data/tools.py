"""
LangChain tools for Ask Your Data:
1. describe_schema: Inspects dataset columns, dtypes, and sample values
2. run_pandas_query: Sandboxed pandas code execution
3. make_chart: Generates Plotly chart specification from query results
"""

import json
from typing import Optional, Dict, Any, List
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
from langchain_core.tools import tool

from ask_your_data.data_loader import load_dataset, format_schema_for_prompt
from ask_your_data.sandbox import SandboxedPandasExecutor, ExecutionResult

# State cache for last executed query dataframe
_LATEST_QUERY_DF: Optional[pd.DataFrame] = None
_LATEST_QUERY_CODE: Optional[str] = None
_LATEST_CHART_SPEC: Optional[Dict[str, Any]] = None

# Dealership Brand Palette
DEALERSHIP_PALETTE = [
    "#0B5394",  # Primary Navy
    "#E45756",  # Coral / Red Accent
    "#54A24B",  # Success Green
    "#EECA3B",  # Amber Warning
    "#72B7B2",  # Modern Teal
    "#AF7AA1",  # Soft Violet
    "#FF9DA7",  # Rose
    "#9C755F",  # Warm Bronze
]


def get_latest_query_df() -> Optional[pd.DataFrame]:
    """Retrieve the DataFrame generated by the most recent query."""
    return _LATEST_QUERY_DF


def set_latest_query_df(df: Optional[pd.DataFrame], code: Optional[str] = None) -> None:
    """Store the DataFrame from the most recent query."""
    global _LATEST_QUERY_DF, _LATEST_QUERY_CODE
    _LATEST_QUERY_DF = df
    if code:
        _LATEST_QUERY_CODE = code


def get_latest_chart_spec() -> Optional[Dict[str, Any]]:
    """Retrieve the most recent chart spec."""
    return _LATEST_CHART_SPEC


def set_latest_chart_spec(spec: Optional[Dict[str, Any]]) -> None:
    """Store the most recent chart spec."""
    global _LATEST_CHART_SPEC
    _LATEST_CHART_SPEC = spec


@tool
def describe_schema(filter_pattern: str = "") -> str:
    """
    Returns columns, data types, unique counts, and sample values of the car dealership dataset.
    Use this tool before writing any query to verify actual column names and categories.
    Optional argument 'filter_pattern' can be passed to search for specific column names.
    """
    df = load_dataset()
    pattern = filter_pattern.strip() if filter_pattern else None
    return format_schema_for_prompt(filter_pattern=pattern, df=df)


@tool
def run_pandas_query(code: str) -> str:
    """
    Executes Python/pandas code against the dealership dataset ('df') inside a secure sandbox.
    Code must be read-only and assign its output to 'result' or return an expression.
    Returns the tabular result, row count, execution time, and any error message.
    """
    global _LATEST_QUERY_DF, _LATEST_QUERY_CODE
    df = load_dataset()
    executor = SandboxedPandasExecutor()

    exec_result: ExecutionResult = executor.run(code, df)

    if not exec_result.success:
        return f"ERROR: {exec_result.error}"

    # Cache result for downstream chart tool
    _LATEST_QUERY_DF = exec_result.df_result
    _LATEST_QUERY_CODE = code

    # Format output for LLM
    if exec_result.df_result is not None:
        if exec_result.df_result.empty:
            return "QUERY RESULT: 0 rows returned (empty DataFrame). Check filter values and casing."
        
        preview_text = exec_result.df_result.head(15).to_string(index=False)
        return (
            f"QUERY SUCCESS ({exec_result.execution_time_ms:.1f}ms)\n"
            f"Rows: {exec_result.row_count} | Columns: {exec_result.column_names}\n\n"
            f"Result Table Preview:\n{preview_text}"
        )

    return f"QUERY SUCCESS: {exec_result.output}"


@tool
def make_chart(
    chart_type: str,
    x_col: str,
    y_col: Optional[str] = None,
    color_col: Optional[str] = None,
    title: Optional[str] = None,
    orientation: str = "v",
) -> str:
    """
    Generates an interactive Plotly chart spec for the most recent query result.
    Supported chart_type: 'bar', 'line', 'scatter', 'pie', 'donut', 'box', 'histogram'.
    'x_col': column for X axis (or categories for pie).
    'y_col': column for Y axis (values).
    'color_col': column for grouping/color breakdown (optional).
    'title': custom chart title.
    'orientation': 'v' (vertical) or 'h' (horizontal).
    """
    global _LATEST_QUERY_DF, _LATEST_CHART_SPEC
    if _LATEST_QUERY_DF is None or _LATEST_QUERY_DF.empty:
        return "ERROR: No recent query result DataFrame found to build a chart. Run run_pandas_query first."

    df = _LATEST_QUERY_DF.copy()
    ctype = chart_type.strip().lower()

    # Column existence check
    available_cols = df.columns.tolist()
    if x_col not in available_cols:
        # Fall back to first column if column name mismatch
        if len(available_cols) > 0:
            x_col = available_cols[0]
        else:
            return f"ERROR: Column '{x_col}' not found in result DataFrame columns: {available_cols}"

    if y_col and y_col not in available_cols:
        if len(available_cols) > 1:
            y_col = available_cols[1]
        else:
            y_col = None

    if color_col and color_col not in available_cols:
        color_col = None

    chart_title = title or f"{chart_type.title()} Analysis by {x_col}"

    try:
        fig = None
        if ctype in ["bar", "column"]:
            if orientation == "h" and y_col:
                fig = px.bar(
                    df,
                    x=y_col,
                    y=x_col,
                    color=color_col,
                    orientation="h",
                    title=chart_title,
                    color_discrete_sequence=DEALERSHIP_PALETTE,
                )
            else:
                fig = px.bar(
                    df,
                    x=x_col,
                    y=y_col,
                    color=color_col,
                    title=chart_title,
                    color_discrete_sequence=DEALERSHIP_PALETTE,
                    text_auto=True if y_col else False,
                )

        elif ctype in ["line", "trend"]:
            fig = px.line(
                df,
                x=x_col,
                y=y_col,
                color=color_col,
                title=chart_title,
                markers=True,
                color_discrete_sequence=DEALERSHIP_PALETTE,
            )

        elif ctype in ["scatter", "bubble"]:
            fig = px.scatter(
                df,
                x=x_col,
                y=y_col,
                color=color_col,
                title=chart_title,
                color_discrete_sequence=DEALERSHIP_PALETTE,
            )

        elif ctype in ["pie", "donut"]:
            hole = 0.4 if ctype == "donut" else 0.0
            fig = px.pie(
                df,
                names=x_col,
                values=y_col,
                title=chart_title,
                hole=hole,
                color_discrete_sequence=DEALERSHIP_PALETTE,
            )

        elif ctype in ["box"]:
            fig = px.box(
                df,
                x=x_col,
                y=y_col,
                color=color_col,
                title=chart_title,
                color_discrete_sequence=DEALERSHIP_PALETTE,
            )

        elif ctype in ["hist", "histogram"]:
            fig = px.histogram(
                df,
                x=x_col,
                y=y_col,
                color=color_col,
                title=chart_title,
                color_discrete_sequence=DEALERSHIP_PALETTE,
            )

        else:
            # Fallback default bar
            fig = px.bar(
                df,
                x=x_col,
                y=y_col,
                color=color_col,
                title=chart_title,
                color_discrete_sequence=DEALERSHIP_PALETTE,
            )

        # Apply dealership design styling
        fig.update_layout(
            template="plotly_white",
            margin=dict(l=40, r=40, t=50, b=40),
            title_font=dict(size=16, family="Arial, sans-serif"),
            legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
            font=dict(family="Arial, sans-serif", size=12),
        )

        # Store JSON spec
        chart_dict = json.loads(fig.to_json())
        _LATEST_CHART_SPEC = chart_dict

        return f"SUCCESS: Generated {chart_type} chart titled '{chart_title}'. Chart spec is ready for rendering."

    except Exception as e:
        return f"ERROR generating chart: {str(e)}"
